'use strict';
const express=require('express'), jwt=require('jsonwebtoken'), {Pool}=require('pg'), helmet=require('helmet'), {rateLimit}=require('express-rate-limit');
const {DATABASE_URL,JWT_SECRET,PORT='3001'}=process.env;
if(!DATABASE_URL||!JWT_SECRET||Buffer.byteLength(JWT_SECRET)<32) throw Error('DATABASE_URL and a random JWT_SECRET of at least 32 bytes are required');
const pool=new Pool({connectionString:DATABASE_URL,max:10,connectionTimeoutMillis:5000,idleTimeoutMillis:30000,statement_timeout:5000});
pool.on('error',error=>console.error('Idle database connection failed',error.message));
const ddl=`
CREATE TABLE IF NOT EXISTS roles(id smallint PRIMARY KEY,name varchar(16) UNIQUE NOT NULL CHECK(name IN ('Admin','User')));
INSERT INTO roles VALUES(1,'Admin'),(2,'User') ON CONFLICT DO NOTHING;
CREATE TABLE IF NOT EXISTS users(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK(id BETWEEN 1 AND 4294967295),
 role_id smallint NOT NULL DEFAULT 2 REFERENCES roles(id),
 email varchar(254) UNIQUE NOT NULL,
 token_version integer NOT NULL DEFAULT 0 CHECK(token_version>=0));
CREATE INDEX IF NOT EXISTS idx_users_role ON users(role_id);
CREATE TABLE IF NOT EXISTS tasks(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK(id BETWEEN 1 AND 4294967295),
 user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 title varchar(200) NOT NULL CHECK(length(trim(title))>0),description text NOT NULL DEFAULT '',
 status varchar(16) NOT NULL DEFAULT 'todo' CHECK(status IN ('todo','in-progress','done')),
 priority varchar(10) NOT NULL DEFAULT 'medium' CHECK(priority IN ('low','medium','high')),
 due_date date,
 created_at timestamptz NOT NULL DEFAULT now(),updated_at timestamptz NOT NULL DEFAULT now());
CREATE INDEX IF NOT EXISTS idx_tasks_owner_status_id ON tasks(user_id,status,id DESC);
CREATE INDEX IF NOT EXISTS idx_tasks_owner_id ON tasks(user_id,id DESC);
CREATE INDEX IF NOT EXISTS idx_tasks_status_id ON tasks(status,id DESC);`;
const fail=(status,message)=>Object.assign(new Error(message),{status});
function integer(value,fallback,max) {
  if(value===undefined) return fallback;
  if(typeof value!=='string'||!/^[1-9][0-9]{0,9}$/.test(value)||Number(value)>max) throw fail(422,'Invalid pagination');
  return Number(value);
}
function authenticate(req,res,next) {
  const bearer=/^Bearer (\S+)$/.exec(req.get('authorization')||'');
  if(!bearer) return next(fail(401,'Authentication required'));
  try {
    const claims=jwt.verify(bearer[1],JWT_SECRET,{algorithms:['HS256'],issuer:'goqii-api',audience:'goqii-web'});
    if(typeof claims.sub!=='string'||!/^[1-9][0-9]{0,9}$/.test(claims.sub)||Number(claims.sub)>4294967295||!Number.isInteger(claims.exp)||!Number.isInteger(claims.ver)) throw Error();
    req.auth=claims;
    next();
  } catch {next(fail(401,'Invalid or expired token'));}
}
async function main() {
  if(process.argv.includes('--init')) {await pool.query(ddl);await pool.end();return;}
  await pool.query('SELECT 1 FROM roles LIMIT 1');
  const app=express();
  app.disable('x-powered-by'); app.use(helmet());
  app.use((req,res,next)=>{res.set('Cache-Control','no-store');next();});
  app.use(rateLimit({windowMs:60000,limit:120,standardHeaders:'draft-7',legacyHeaders:false,message:{error:'Too many requests'}}));
  app.get('/api/tasks',authenticate,async(req,res,next)=>{
    let client,transaction=false;
    try {
      const claims=req.auth;
      const page=integer(req.query.page,1,10000),limit=integer(req.query.limit,10,100),status=req.query.status;
      if(status!==undefined&&!['todo','in-progress','done'].includes(status)) throw fail(422,'Invalid status');
      client=await pool.connect();
      await client.query('BEGIN ISOLATION LEVEL REPEATABLE READ READ ONLY'); transaction=true;
      const {rows:[user]}=await client.query('SELECT u.id,u.token_version,r.name AS role FROM users u JOIN roles r ON r.id=u.role_id WHERE u.id=$1',[claims.sub]);
      if(!user||user.token_version!==claims.ver) throw fail(401,'Session revoked');
      if(!['Admin','User'].includes(user.role)) throw fail(403,'Forbidden');
      const values=[],where=[];
      if(user.role!=='Admin') {values.push(user.id);where.push(`user_id=$${values.length}`);}
      if(status!==undefined) {values.push(status);where.push(`status=$${values.length}`);}
      const filter=where.length?` WHERE ${where.join(' AND ')}`:'';
      const {rows:[count]}=await client.query(`SELECT count(*) AS total FROM tasks${filter}`,values);
      const {rows:items}=await client.query(`SELECT id,user_id,title,description,status,priority,due_date,created_at,updated_at FROM tasks${filter} ORDER BY id DESC LIMIT $${values.length+1} OFFSET $${values.length+2}`,[...values,limit,(page-1)*limit]);
      await client.query('COMMIT');transaction=false;
      res.json({items:items.map(t=>({...t,id:Number(t.id),user_id:Number(t.user_id)})),total:Number(count.total),page,limit});
    } catch(error) {
      if(transaction) {try {await client.query('ROLLBACK');}catch {client.release(true);client=null;}}
      next(error);
    } finally {client?.release();}
  });
  app.use((req,res)=>res.status(404).json({error:'Not found'}));
  app.use((error,req,res,next)=>{if(!error.status) console.error(error);res.status(error.status||500).json({error:error.status?error.message:'Internal server error'});});
  const server=app.listen(Number(PORT),'0.0.0.0');
  for(const signal of ['SIGINT','SIGTERM']) process.once(signal,()=>{
    server.close(()=>pool.end().then(()=>process.exit(0)));
    setTimeout(()=>process.exit(1),10000).unref();
  });
}
main().catch(async error=>{console.error(error);await pool.end();process.exitCode=1;});
